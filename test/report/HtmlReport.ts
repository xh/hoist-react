// Filter tests by name - hide non-matching tests, then any suite, file, or package left empty.
const SCRIPT = `
const input = document.getElementById('filter'), matches = document.getElementById('matches');
input.addEventListener('input', () => {
  const q = input.value.trim().toLowerCase();
  let n = 0;
  document.querySelectorAll('li.test').forEach(li => {
    const path = [li.textContent];
    for (let p = li.parentElement.closest('li.suite'); p; p = p.parentElement.closest('li.suite'))
      path.push(p.querySelector('.suite-name').textContent);
    const hit = !q || path.join(' ').toLowerCase().includes(q);
    li.classList.toggle('hidden', !hit);
    if (hit) n++;
  });
  const prune = sel => document.querySelectorAll(sel).forEach(el =>
    el.classList.toggle('hidden', !!q && !el.querySelector('li.test:not(.hidden)')));
  prune('li.suite'); prune('details.file'); prune('details.pkg');
  if (q) document.querySelectorAll('details.pkg:not(.hidden), details.file:not(.hidden)').forEach(d => d.open = true);
  matches.textContent = q ? n + ' matching tests' : '';
});
const toggle = document.getElementById('toggle');
toggle.addEventListener('click', () => {
  const open = toggle.textContent === 'Expand all';
  document.querySelectorAll('details.pkg, details.file').forEach(d => d.open = open);
  toggle.textContent = open ? 'Collapse all' : 'Expand all';
});
`;
