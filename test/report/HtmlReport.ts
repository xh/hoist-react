import {escape, groupBy} from 'lodash';
import {fmtDuration} from './MarkdownReport';
import {fullName, type ReportFile, type ReportTest, type TestReport} from './TestReporter';

/**
 * Render a test report as a single, self-contained HTML page - no external assets, so it works
 * when opened from a downloaded CI artifact as well as from GitHub Pages.
 */
export function renderHtml(report: TestReport): string {
    const {totals, files, git} = report,
        passing = !totals.failed && !report.loadFailures && !report.unhandledErrors.length,
        pkgs = groupBy(files, it => it.pkg),
        status = passing
            ? `All ${fmtNum(totals.passed)} tests passing`
            : `${fmtNum(totals.failed + report.loadFailures)} failing`;

    const meta = [
        git.branch ? `<span>${escape(git.branch)}</span>` : null,
        git.sha ? link(commitUrl(report), `<code>${git.sha.slice(0, 8)}</code>`) : null,
        `<span>${new Date(report.timestamp).toUTCString()}</span>`,
        git.runUrl ? link(git.runUrl, 'View CI run') : null
    ];

    return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Hoist React Unit Tests</title>
<style>${CSS}</style>
</head>
<body class="${passing ? 'passing' : 'failing'}">
<header>
  <div class="wrap">
    <div class="brand">Hoist React <span>Unit Tests</span></div>
    <h1><span class="mark">${passing ? '✓' : '✗'}</span>${status}</h1>
    <div class="meta">${meta.filter(Boolean).join('<i>·</i>')}</div>
    <p class="intro">Unit tests for the <code>@xh/hoist</code> library, run on Vitest. Tests compile
    Hoist with the same SWC decorator settings apps use, and run its real services against an
    in-memory fake of the hoist-core server.</p>
  </div>
</header>
<main class="wrap">
  <section class="tiles">
    ${tile(fmtNum(totals.total), 'Tests')}
    ${tile(fmtNum(files.length), 'Spec files')}
    ${tile(fmtNum(Object.keys(pkgs).length), 'Packages')}
    ${tile(fmtDuration(report.duration), 'Duration')}
    ${totals.knownBugs ? tile(fmtNum(totals.knownBugs), 'Known bugs', 'bug') : ''}
    ${totals.failed ? tile(fmtNum(totals.failed), 'Failed', 'fail') : ''}
  </section>
  ${failuresSection(report)}
  <section class="tests">
    <div class="toolbar">
      <h2>Tests by package</h2>
      <input id="filter" type="search" placeholder="Filter tests..." autocomplete="off">
      <span id="matches"></span>
      <button id="toggle" type="button">Expand all</button>
    </div>
    ${Object.entries(pkgs)
        .map(([pkg, pkgFiles]) => packageSection(report, pkg, pkgFiles))
        .join('\n')}
  </section>
</main>
<footer class="wrap">Generated by hoist-react's test reporter (test/report) · ${link(
        'https://github.com/xh/hoist-react/blob/develop/docs/unit-testing.md',
        'About these tests'
    )}</footer>
<script>${SCRIPT}</script>
</body>
</html>
`;
}

//------------------------
// Sections
//------------------------
function failuresSection(report: TestReport): string {
    const items = [];
    report.files.forEach(file => {
        file.loadErrors.forEach(msg =>
            items.push(
                `<div class="failure"><h3>💥 Could not run ${escape(file.path)}</h3>${pre(msg)}</div>`
            )
        );
        file.tests
            .filter(it => it.state === 'failed')
            .forEach(test => {
                const [err] = test.errors;
                items.push(`<div class="failure">
                    <h3>✗ ${escape(fullName(test))}</h3>
                    <div class="where">${fileLink(report, file, err?.line ?? test.line)}</div>
                    ${err ? pre(err.message) : ''}
                    ${err?.diff ? diffPre(err.diff) : ''}
                </div>`);
            });
    });
    report.unhandledErrors.forEach(msg =>
        items.push(`<div class="failure"><h3>💥 Unhandled error</h3>${pre(msg)}</div>`)
    );
    return items.length
        ? `<section class="failures"><h2>Failures</h2>${items.join('')}</section>`
        : '';
}

function packageSection(report: TestReport, pkg: string, files: ReportFile[]): string {
    const tests = files.flatMap(it => it.tests),
        failed =
            tests.filter(it => it.state === 'failed').length +
            files.filter(it => it.loadErrors.length).length,
        passPct = tests.length ? ((tests.length - failed) / tests.length) * 100 : 100;

    return `<details class="pkg"${failed ? ' open' : ''}>
  <summary>
    <span class="pkg-name">${escape(pkg)}</span>
    <span class="bar"><span style="width:${passPct.toFixed(1)}%"></span></span>
    <span class="count">${plural(files.length, 'file')} · ${plural(tests.length, 'test')}${failed ? ` · <b class="fail">${failed} failed</b>` : ''}</span>
  </summary>
  ${files.map(file => fileSection(report, file)).join('\n')}
</details>`;
}

function fileSection(report: TestReport, file: ReportFile): string {
    const failed = file.tests.some(it => it.state === 'failed') || file.loadErrors.length;
    return `<details class="file"${failed ? ' open' : ''}>
  <summary>${escape(file.path.split('/').pop())}<span class="count">${file.tests.length}</span>${fileLink(report, file, null, '↗')}</summary>
  ${renderTree(report, file, buildTree(file.tests))}
</details>`;
}

//------------------------
// Describe-block tree
//------------------------
interface TreeNode {
    suites: Map<string, TreeNode>;
    tests: ReportTest[];
}

function buildTree(tests: ReportTest[]): TreeNode {
    const root: TreeNode = {suites: new Map(), tests: []};
    tests.forEach(test => {
        let node = root;
        test.suites.forEach(name => {
            if (!node.suites.has(name)) node.suites.set(name, {suites: new Map(), tests: []});
            node = node.suites.get(name);
        });
        node.tests.push(test);
    });
    return root;
}

function renderTree(report: TestReport, file: ReportFile, node: TreeNode): string {
    const suites = [...node.suites.entries()].map(
            ([name, child]) =>
                `<li class="suite"><span class="suite-name">${escape(name)}</span>${renderTree(report, file, child)}</li>`
        ),
        tests = node.tests.map(test => {
            const cls = test.state === 'passed' && test.knownBug ? 'bug' : test.state,
                icon = {passed: '✓', failed: '✗', skipped: '–', bug: '🐞'}[cls],
                title = test.knownBug ? ' title="Known bug - expected to fail until fixed"' : '';
            return `<li class="test ${cls}"${title}><span class="icon">${icon}</span>${escape(test.name)}<span class="dur">${fmtDuration(test.duration)}</span></li>`;
        });
    return `<ul>${[...tests, ...suites].join('')}</ul>`;
}

//------------------------
// Helpers
//------------------------
function tile(value: string, label: string, cls = ''): string {
    return `<div class="tile ${cls}"><div class="value">${value}</div><div class="label">${label}</div></div>`;
}

function link(href: string, html: string): string {
    return `<a href="${escape(href)}" target="_blank" rel="noopener">${html}</a>`;
}

function fileLink(report: TestReport, file: ReportFile, line: number, label?: string): string {
    const text = label ?? escape(line ? `${file.path}:${line}` : file.path),
        {blobUrl} = report.git;
    if (!blobUrl) return label ? '' : `<code>${text}</code>`;
    return link(
        `${blobUrl}/${file.path}${line ? `#L${line}` : ''}`,
        label ? text : `<code>${text}</code>`
    );
}

function commitUrl(report: TestReport): string {
    const {blobUrl, sha} = report.git;
    return blobUrl ? blobUrl.replace(/\/blob\/.*$/, `/commit/${sha}`) : null;
}

function pre(text: string): string {
    return `<pre>${escape(text.trim())}</pre>`;
}

function diffPre(diff: string): string {
    const lines = diff
        .trim()
        .split('\n')
        .map(line => {
            const cls = line.startsWith('+') ? 'add' : line.startsWith('-') ? 'del' : '';
            return `<span class="${cls}">${escape(line)}</span>`;
        });
    return `<pre class="diff">${lines.join('\n')}</pre>`;
}

function fmtNum(n: number): string {
    return n.toLocaleString('en-US');
}

function plural(n: number, noun: string): string {
    return `${fmtNum(n)} ${noun}${n === 1 ? '' : 's'}`;
}

