//
// Generates `kit/pdfjs/pdf_viewer.css` from the pdf.js viewer stylesheet in `pdfjs-dist`.
//
// The source stylesheet also styles Mozilla's full viewer app, with unscoped rules for generic
// selectors such as `button` and `.dialog`. This script scopes every rule to `.xh-pdf-viewer`,
// so none of them apply outside a PdfViewer:
//  - `:root` rules move onto `.xh-pdf-viewer`, minus `color-scheme`, which Hoist's theme owns.
//  - All other top-level selectors become descendants of `.xh-pdf-viewer`.
//  - Images are inlined as data URIs, so the output needs no asset resolution.
//
// Run via `pnpm generate:pdfjs-css` after upgrading pdfjs-dist. `pnpm check:vendored` (a CI step)
// verifies the checked-in file matches.
//
import {readFileSync, writeFileSync} from 'fs';
import {join} from 'path';
import {fileURLToPath} from 'url';
import postcss from 'postcss';

const SRC_DIR = 'node_modules/pdfjs-dist/legacy/web',
    SCOPE = '.xh-pdf-viewer',
    SKIP_AT_RULES = ['keyframes', 'font-face', 'property', 'counter-style'],
    MIME_TYPES = {svg: 'image/svg+xml', gif: 'image/gif', png: 'image/png'};

export const DEST = 'kit/pdfjs/pdf_viewer.css';

export function generatePdfJsCss() {
    const {version} = JSON.parse(readFileSync('node_modules/pdfjs-dist/package.json', 'utf8')),
        root = postcss.parse(readFileSync(join(SRC_DIR, 'pdf_viewer.css'), 'utf8'));

    scopeRules(root);
    root.walkDecls(decl => {
        decl.value = decl.value.replace(/url\(\s*["']?(images\/[^"')]+)["']?\s*\)/g, (_, path) =>
            inlineImage(path)
        );
    });

    const header =
        `/* Generated by scripts/generate-pdfjs-css.mjs from pdfjs-dist ${version} ` +
        `(legacy/web/pdf_viewer.css). Do not edit. */\n`;
    return header + root.toString();
}

function scopeRules(container) {
    container.each(node => {
        if (node.type === 'rule') {
            node.selectors = node.selectors.map(scopeSelector);
            if (node.selector === SCOPE) {
                node.walkDecls('color-scheme', decl => decl.remove());
            }
        } else if (node.type === 'atrule' && node.nodes && !SKIP_AT_RULES.includes(node.name)) {
            scopeRules(node);
        }
    });
}

function scopeSelector(selector) {
    return selector.startsWith(':root')
        ? SCOPE + selector.slice(':root'.length)
        : `${SCOPE} ${selector}`;
}

function inlineImage(path) {
    const ext = path.split('.').pop(),
        data = readFileSync(join(SRC_DIR, path)).toString('base64');
    return `url("data:${MIME_TYPES[ext]};base64,${data}")`;
}

// Write when run directly, rather than imported by check-vendored.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(DEST, generatePdfJsCss());
    console.log(`Wrote ${DEST}`);
}
